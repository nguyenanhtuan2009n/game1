// Helper: Kiểm tra một kỹ năng đã mở khóa hay chưa dựa trên nhân vật
export function isSkillUnlockedForCharacter(char: Character, skill: CatalogSkill): boolean {
  if (skill.category === 'magic') {
    const elementKey = 
      skill.subCategory.includes('Hỏa') ? 'fire' :
      skill.subCategory.includes('Nước') || skill.subCategory.includes('Thủy') ? 'water' :
      skill.subCategory.includes('Đất') || skill.subCategory.includes('Thổ') ? 'earth' :
      skill.subCategory.includes('Gió') || skill.subCategory.includes('Phong') ? 'wind' :
      skill.subCategory.includes('Trị Liệu') ? 'healing' : '';
    
    if (elementKey) {
      const charTier = (char.magic as any)[elementKey] || 'Chưa học';
      const charRank = TIER_RANK_MAP[charTier as PowerTier] || 0;
      return charRank >= skill.tier;
    }

    // Hybrid magic
    if (skill.id === 'skill_combo_magma') {
      return (TIER_RANK_MAP[char.magic.fire] || 0) >= 1 && (TIER_RANK_MAP[char.magic.earth] || 0) >= 1;
    }
    if (skill.id === 'skill_combo_lightning') {
      return (TIER_RANK_MAP[char.magic.water] || 0) >= 1 && (TIER_RANK_MAP[char.magic.wind] || 0) >= 1;
    }
    if (skill.id === 'skill_combo_firestorm') {
      return (TIER_RANK_MAP[char.magic.fire] || 0) >= 1 && (TIER_RANK_MAP[char.magic.wind] || 0) >= 1;
    }
  }

  if (skill.category === 'sword') {
    const styleKey = 
      skill.subCategory.includes('Kiếm Thần') ? 'swordGod' :
      skill.subCategory.includes('Thủy Thần') ? 'waterGod' :
      skill.subCategory.includes('Bắc Thần') ? 'northGod' : '';
    
    if (styleKey) {
      const charTier = (char.swordsmanship as any)[styleKey] || 'Chưa học';
      const charRank = TIER_RANK_MAP[charTier as PowerTier] || 0;
      return charRank >= skill.tier;
    }
  }

  if (skill.category === 'hybrid' || skill.category === 'special') {
    if (skill.id === 'skill_combo_magic_sword') {
      const hasMagic = ['fire', 'water', 'wind'].some(e => TIER_RANK_MAP[(char.magic as any)[e] as PowerTier] >= 1);
      const hasSword = ['swordGod', 'waterGod', 'northGod'].some(s => TIER_RANK_MAP[(char.swordsmanship as any)[s] as PowerTier] >= 1);
      const hasCoating = char.progression?.magicKnight?.elementalCoating && char.progression.magicKnight.elementalCoating !== 'Chưa học';
      return (hasMagic && hasSword) || !!hasCoating;
    }
    if (skill.id === 'skill_combo_foresight') {
      return !!char.progression?.demonEyes?.foresightEye;
    }
  }

  return false;
}

// Convert CatalogSkill to TurnChoice for combat execution
export function catalogSkillToTurnChoice(
  skill: CatalogSkill,
  char: Character,
  opponentName: string = 'đối thủ'
): TurnChoice {
  const isMagic = skill.category === 'magic' || skill.subCategory.includes('Ma Pháp') || skill.subCategory.includes('Hệ');
  const isSword = skill.category === 'sword' || skill.subCategory.includes('Kiếm');

  let costLabel = '';
  if (skill.costMp > 0 && skill.costStamina > 0) {
    costLabel = `[${skill.costMp} MP + ${skill.costStamina} Thể lực]`;
  } else if (skill.costMp > 0) {
    costLabel = `[${skill.costMp} MP]`;
  } else if (skill.costStamina > 0 && skill.costTouki > 0) {
    costLabel = `[${skill.costStamina} Thể lực + ${skill.costTouki} Đấu Khí]`;
  } else if (skill.costStamina > 0) {
    costLabel = `[${skill.costStamina} Thể lực]`;
  }

  return {
    id: skill.id,
    label: `[${skill.subCategory}] ${skill.name} - ${skill.tierName.split(' ')[0]} ${costLabel}`,
    actionText: `[${skill.name} - ${skill.tierName.split(' ')[0]}: ${costLabel}]: ${skill.description.replace('đối thủ', opponentName).replace('kẻ địch', opponentName)}`,
    riskLevel: skill.tier >= 5 ? 'fatal' : skill.tier >= 3 ? 'dangerous' : 'moderate',
    category: 'combat',
    combatBranch: 'A_OFFENSE',
    combatRole: 'attack',
    combatSubCategory: isMagic ? 'A1. Ma Pháp Tấn Công' : 'A2. Kiếm Pháp Tấn Công',
    combatTactic: (skill.tactic as any) || (isMagic ? 'kite_magic' : 'rush'),
    costMp: skill.costMp,
    costStamina: skill.costStamina,
    costTouki: skill.costTouki,
    skillTier: skill.tier,
    skillTierName: skill.tierName,
    offensiveGroup: isMagic ? 'magic' : isSword ? 'sword' : 'hybrid',
    offensiveSubCategory: 'skills',
    damageDisplay: skill.damageEstimate,
    consequenceHint: skill.effectHint,
  };
}
